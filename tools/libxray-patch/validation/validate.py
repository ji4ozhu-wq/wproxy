#!/usr/bin/env python3
"""Validates a locally built libXray (with tools/libxray-patch applied):

1. every config generated by the app's XrayConfigBuilder is accepted by libXray testXray,
2. the injected `getTrafficStats` method is registered and reports real byte counters
   while Xray runs a SOCKS inbound (proves the C6 traffic path).

Usage: python3 validate.py <driver binary> <config directory>
"""
import functools
import glob
import http.server
import json
import os
import shutil
import subprocess
import sys
import tempfile
import threading

SOCKS_PORT = 18080
HTTP_PORT = 18081


class Driver:
    def __init__(self, binary):
        self.proc = subprocess.Popen([binary], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                     stderr=subprocess.DEVNULL, text=True, bufsize=1)

    def request(self, command):
        self.proc.stdin.write(command + "\n")
        self.proc.stdin.flush()
        # Xray-core writes warnings to stdout; skip anything that is not our protocol.
        while True:
            line = self.proc.stdout.readline()
            if line == "":
                raise RuntimeError("driver exited unexpectedly")
            line = line.strip()
            if line.startswith("RESP "):
                return json.loads(line[5:])

    def close(self):
        try:
            self.request("quit")
        except Exception:
            pass
        self.proc.kill()


def socks_config(path):
    config = {
        "log": {"loglevel": "none"},
        "stats": {},
        "policy": {"system": {"statsInboundUplink": True, "statsInboundDownlink": True}},
        "inbounds": [{
            "tag": "socks-in", "protocol": "socks", "listen": "127.0.0.1", "port": SOCKS_PORT,
            "settings": {"auth": "noauth", "udp": False}
        }],
        "outbounds": [{"tag": "direct", "protocol": "freedom", "settings": {}}],
        "routing": {"domainStrategy": "AsIs",
                    "rules": [{"type": "field", "network": "tcp,udp", "outboundTag": "direct"}]}
    }
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(config, handle)


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    driver_binary, config_dir = sys.argv[1], sys.argv[2]
    failures = []
    driver = Driver(driver_binary)

    version = driver.request("version")
    print(f"libXray version: {version.get('data', {}).get('version')}")

    before = driver.request("stats")
    if before.get("success") is False and "xray is not running" in before.get("error", ""):
        print("PASS  getTrafficStats method is registered (fork patch applied)")
    else:
        failures.append(f"getTrafficStats not registered: {before}")

    configs = sorted(glob.glob(os.path.join(config_dir, "*.json")))
    if not configs:
        failures.append("no generated configs found")
    for path in configs:
        result = driver.request("test " + path)
        name = os.path.basename(path)
        if result.get("success"):
            print(f"PASS  testXray accepted {name}")
        else:
            failures.append(f"{name}: {result.get('error')}")
            print(f"FAIL  testXray rejected {name}: {result.get('error')}")

    workdir = tempfile.mkdtemp(prefix="wuji-traffic-")
    payload = os.urandom(64 * 1024)
    payload_path = os.path.join(workdir, "payload.bin")
    with open(payload_path, "wb") as handle:
        handle.write(payload)
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=workdir)
    server = http.server.ThreadingHTTPServer(("127.0.0.1", HTTP_PORT), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()

    socks_path = os.path.join(workdir, "socks-config.json")
    socks_config(socks_path)
    run_result = driver.request("run " + socks_path)
    if not run_result.get("success"):
        failures.append(f"runXray(socks) failed: {run_result.get('error')}")
    else:
        state = driver.request("state")
        if not state.get("data", {}).get("running"):
            failures.append("runXray reported success but getXrayState is not running")
        curl = subprocess.run(
            ["curl", "-sS", "--max-time", "20", "--socks5", f"127.0.0.1:{SOCKS_PORT}",
             f"http://127.0.0.1:{HTTP_PORT}/payload.bin"],
            capture_output=True,
        )
        if curl.returncode != 0 or len(curl.stdout) != len(payload):
            failures.append(f"curl through Xray socks failed rc={curl.returncode} bytes={len(curl.stdout)}")
        stats = driver.request("stats socks-in")
        if not stats.get("success"):
            failures.append(f"getTrafficStats failed while running: {stats.get('error')}")
        else:
            data = stats.get("data", {})
            uplink, downlink = data.get("uplink", 0), data.get("downlink", 0)
            print(f"      getTrafficStats -> uplink={uplink} downlink={downlink}")
            if uplink > 0 and downlink >= len(payload):
                print("PASS  getTrafficStats reports real uplink/downlink counters")
            else:
                failures.append(f"traffic counters suspicious: uplink={uplink} downlink={downlink}")
        stop_result = driver.request("stop")
        if not stop_result.get("success"):
            failures.append(f"stopXray failed: {stop_result.get('error')}")
        after = driver.request("stats")
        if after.get("success") is False and "xray is not running" in after.get("error", ""):
            print("PASS  getTrafficStats rejects when the kernel is stopped")
        else:
            failures.append(f"stats after stop unexpected: {after}")

    server.shutdown()
    shutil.rmtree(workdir, ignore_errors=True)
    driver.close()

    print()
    if failures:
        print(f"FAILED ({len(failures)})")
        for failure in failures:
            print(" -", failure)
        return 1
    print(f"ALL CHECKS PASSED ({len(configs)} configs + traffic counters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
